import os
import joblib
import pandas as pd


# ============================================================
# CODEALPHA - CREDIT SCORING MODEL
# CREDIT RISK PREDICTION SYSTEM
# ============================================================

MODEL_PATH = "models/credit_scoring_model.pkl"
THRESHOLD_PATH = "models/decision_threshold.txt"


print("=" * 60)
print("CODEALPHA - CREDIT RISK PREDICTION")
print("=" * 60)


# ------------------------------------------------------------
# 1. Check model files
# ------------------------------------------------------------
if not os.path.exists(MODEL_PATH):
    print("Error: Trained model not found.")
    print("Please run: python src\\save_model.py")
    exit()

if not os.path.exists(THRESHOLD_PATH):
    print("Error: Decision threshold not found.")
    print("Please run: python src\\save_model.py")
    exit()


# ------------------------------------------------------------
# 2. Load model and threshold
# ------------------------------------------------------------
model = joblib.load(MODEL_PATH)

with open(THRESHOLD_PATH, "r") as file:
    threshold = float(file.read().strip())


# ------------------------------------------------------------
# 3. Get user input
# ------------------------------------------------------------
print("\nEnter the applicant's financial information.")
print("Press Ctrl+C to stop.\n")

try:

    age = float(input("Age: "))

    revolving_utilization = float(
        input("Revolving Utilization of Unsecured Lines: ")
    )

    late_30_59 = float(
        input("Number of Times 30-59 Days Past Due: ")
    )

    debt_ratio = float(
        input("Debt Ratio: ")
    )

    monthly_income = float(
        input("Monthly Income: ")
    )

    open_credit_lines = float(
        input("Number of Open Credit Lines and Loans: ")
    )

    late_90 = float(
        input("Number of Times 90 Days Late: ")
    )

    real_estate_loans = float(
        input("Number of Real Estate Loans or Lines: ")
    )

    late_60_89 = float(
        input("Number of Times 60-89 Days Past Due: ")
    )

    dependents = float(
        input("Number of Dependents: ")
    )


    # --------------------------------------------------------
    # 4. Create input DataFrame
    # --------------------------------------------------------
    input_data = pd.DataFrame([{
        "RevolvingUtilizationOfUnsecuredLines":
            revolving_utilization,

        "age":
            age,

        "NumberOfTime30-59DaysPastDueNotWorse":
            late_30_59,

        "DebtRatio":
            debt_ratio,

        "MonthlyIncome":
            monthly_income,

        "NumberOfOpenCreditLinesAndLoans":
            open_credit_lines,

        "NumberOfTimes90DaysLate":
            late_90,

        "NumberRealEstateLoansOrLines":
            real_estate_loans,

        "NumberOfTime60-89DaysPastDueNotWorse":
            late_60_89,

        "NumberOfDependents":
            dependents
    }])


    # --------------------------------------------------------
    # 5. Predict probability
    # --------------------------------------------------------
    probability = model.predict_proba(input_data)[0][1]

    prediction = int(probability >= threshold)


    # --------------------------------------------------------
    # 6. Display result
    # --------------------------------------------------------
    print("\n" + "=" * 60)
    print("CREDIT RISK PREDICTION")
    print("=" * 60)

    print(f"Risk Probability : {probability * 100:.2f}%")
    print(f"Decision Threshold: {threshold:.2f}")

    print("\nPrediction:")

    if prediction == 1:
        print("⚠️  SERIOUS DELINQUENCY RISK")
    else:
        print("✅ NO SERIOUS DELINQUENCY RISK")

    print("=" * 60)

    print("\nNote:")
    print(
        "This prediction is generated by a machine learning model "
        "trained on historical credit data. It should not be treated "
        "as a guaranteed financial decision."
    )

except ValueError:
    print("\nError: Please enter numeric values only.")

except KeyboardInterrupt:
    print("\n\nPrediction cancelled.")